from __future__ import annotations

import math
import random
from pathlib import Path

import numpy as np
import pandas as pd
import torch
from PIL import Image, ImageEnhance
from torch.utils.data import Dataset
from torchvision.transforms import functional as TF
from torchvision.transforms.functional import InterpolationMode


IMAGENET_MEAN = torch.tensor([0.485, 0.456, 0.406], dtype=torch.float32).view(3, 1, 1)
IMAGENET_STD = torch.tensor([0.229, 0.224, 0.225], dtype=torch.float32).view(3, 1, 1)


class BRISC2025Dataset(Dataset):
    """Paired BRISC2025 segmentation dataset.

    The repository uses a *paired* manifest generated by
    ``scripts/prepare_brisc2025.py``. Required columns are:

    ``split, case_id, image_path, mask_path, tumor_code, plane_code``.

    Paths may be absolute or relative to ``data_root``.
    """

    def __init__(
        self,
        manifest: str | Path,
        split: str,
        data_root: str | Path,
        image_size: int = 256,
        augment: bool = False,
        imagenet_norm: bool = True,
    ) -> None:
        self.manifest_path = Path(manifest)
        self.data_root = Path(data_root)
        self.image_size = int(image_size)
        self.augment = bool(augment)
        self.imagenet_norm = bool(imagenet_norm)

        df = pd.read_csv(self.manifest_path)
        required = {"split", "case_id", "image_path", "mask_path", "tumor_code", "plane_code"}
        missing = required - set(df.columns)
        if missing:
            raise ValueError(
                f"Manifest {self.manifest_path} is missing columns {sorted(missing)}. "
                "Run scripts/prepare_brisc2025.py first."
            )
        self.df = df[df["split"].astype(str).str.lower() == str(split).lower()].copy().reset_index(drop=True)
        if len(self.df) == 0:
            raise ValueError(f"No rows for split={split!r} in {self.manifest_path}")

    def __len__(self) -> int:
        return len(self.df)

    def _resolve(self, p: str) -> Path:
        path = Path(str(p))
        if path.is_absolute():
            return path
        return self.data_root / path

    @staticmethod
    def _safe_gamma(img: Image.Image, gamma: float) -> Image.Image:
        arr = np.asarray(img, dtype=np.float32) / 255.0
        arr = np.power(np.clip(arr, 0.0, 1.0), gamma)
        return Image.fromarray(np.uint8(np.round(arr * 255.0)), mode="L")

    def _augment_pair(self, image: Image.Image, mask: Image.Image) -> tuple[Image.Image, Image.Image]:
        # These are the moderate augmentations described in the paper. Geometric
        # transforms are applied identically to the image and the mask.
        if random.random() < 0.5:
            image = TF.hflip(image)
            mask = TF.hflip(mask)

        angle = random.uniform(-10.0, 10.0)
        image = TF.rotate(image, angle, interpolation=InterpolationMode.BILINEAR, fill=0)
        mask = TF.rotate(mask, angle, interpolation=InterpolationMode.NEAREST, fill=0)

        # Moderate intensity scale/shift.
        if random.random() < 0.5:
            scale = random.uniform(0.90, 1.10)
            image = ImageEnhance.Contrast(image).enhance(scale)
        if random.random() < 0.5:
            shift = random.uniform(-0.08, 0.08)
            arr = np.asarray(image, dtype=np.float32) / 255.0
            arr = np.clip(arr + shift, 0.0, 1.0)
            image = Image.fromarray(np.uint8(np.round(arr * 255.0)), mode="L")
        if random.random() < 0.5:
            gamma = random.uniform(0.90, 1.10)
            image = self._safe_gamma(image, gamma)
        return image, mask

    def __getitem__(self, idx: int):
        row = self.df.iloc[int(idx)]
        image_path = self._resolve(row.image_path)
        mask_path = self._resolve(row.mask_path)
        if not image_path.exists():
            raise FileNotFoundError(f"Image not found: {image_path}")
        if not mask_path.exists():
            raise FileNotFoundError(f"Mask not found: {mask_path}")

        image = Image.open(image_path).convert("L")
        mask = Image.open(mask_path).convert("L")
        image = TF.resize(image, [self.image_size, self.image_size], interpolation=InterpolationMode.BILINEAR, antialias=True)
        mask = TF.resize(mask, [self.image_size, self.image_size], interpolation=InterpolationMode.NEAREST)

        if self.augment:
            image, mask = self._augment_pair(image, mask)

        x = TF.pil_to_tensor(image).float() / 255.0
        x = x.repeat(3, 1, 1)
        if self.imagenet_norm:
            x = (x - IMAGENET_MEAN) / IMAGENET_STD

        y = TF.pil_to_tensor(mask).float() / 255.0
        y = (y >= 0.5).float()

        meta = {
            "case_id": str(row.case_id),
            "tumor_code": str(row.tumor_code).lower(),
            "plane_code": str(row.plane_code).lower(),
            "image_path": str(image_path),
            "mask_path": str(mask_path),
        }
        return x, y, meta
